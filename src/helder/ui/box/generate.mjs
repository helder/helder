// Punctuation.hx from Unicode's data: the code points of General_Category
// Ps, Pe, Pi, Pf and Po (what ::first-letter takes in around its letter,
// CSS Pseudo-Elements 4 §2.3), as ranges. The source is the one
// src/helder/ui/flow/manifest.json checks by hash, in bin/unicode-17.0.0
// (fetched when missing). Run from the repository's root:
// node src/helder/ui/box/generate.mjs
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import {spawnSync} from 'node:child_process'

const version = '17.0.0'
const dir = path.resolve('bin/unicode-' + version)
fs.mkdirSync(dir, {recursive: true})
const name = 'DerivedGeneralCategory.txt'
const file = path.join(dir, name)
if (!fs.existsSync(file)) {
  const r = spawnSync('curl', ['-fsSL', '--max-time', '60', `https://www.unicode.org/Public/${version}/ucd/extracted/${name}`, '-o', file], {encoding: 'utf8'})
  if (r.status !== 0) throw Error(r.stderr)
}
const manifest = JSON.parse(fs.readFileSync('src/helder/ui/flow/manifest.json', 'utf8'))
const sha = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
if (manifest.files[name].sha256 !== sha) throw Error(`${name}: not the hash src/helder/ui/flow/manifest.json has`)

const points = []
for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
  const m = line.split('#')[0].match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\S+)/)
  if (!m || !['Ps', 'Pe', 'Pi', 'Pf', 'Po'].includes(m[3])) continue
  const a = parseInt(m[1], 16), b = m[2] ? parseInt(m[2], 16) : a
  points.push([a, b])
}
points.sort((x, y) => x[0] - y[0])
const ranges = []
for (const [a, b] of points) {
  const last = ranges[ranges.length - 1]
  if (last && last[1] + 1 >= a) last[1] = Math.max(last[1], b)
  else ranges.push([a, b])
}
const lines = []
for (let k = 0; k < ranges.length; k += 8) lines.push('\t\t' + ranges.slice(k, k + 8).map(([a, b]) => `0x${a.toString(16)}, 0x${b.toString(16)}`).join(', '))
fs.writeFileSync('src/helder/ui/box/Punctuation.hx', `package helder.ui.box;

// Generated by generate.mjs from Unicode ${version}'s ${name}: the
// code points of General_Category Ps, Pe, Pi, Pf and Po.
class Punctuation {
	// (first and last of each range, in order)
	static final RANGES:Array<Int> = [
${lines.join(',\n')}
	];

	// Whether a code point is punctuation ::first-letter takes in (Ps, Pe, Pi, Pf, Po).
	public static function is(cp:Int):Bool {
		var lo = 0, hi = (RANGES.length >> 1) - 1;
		while (lo <= hi) {
			var mid = (lo + hi) >> 1;
			if (cp < RANGES[mid * 2]) hi = mid - 1 else if (cp > RANGES[mid * 2 + 1]) lo = mid + 1 else return true;
		}
		return false;
	}
}
`)
console.log(`Punctuation.hx: ${ranges.length} ranges`)
