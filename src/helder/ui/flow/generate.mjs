// LineBreakData.hx from Unicode's data: each code point's Line_Break class
// (UAX #14) with what its rules ask of it besides (East_Asian_Width F, W or
// H; a quotation mark's Pi or Pf; an unassigned Extended_Pictographic), as
// runs of equal values; and a sample of LineBreakTest.txt for the tests
// (tests/flow/line-break-test.txt). Run from the repository's root:
// node src/helder/ui/flow/generate.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';

const version = '17.0.0';
const dir = path.resolve('bin/unicode-' + version);
fs.mkdirSync(dir, {recursive: true});
const sources = {
	'LineBreak.txt': 'ucd/LineBreak.txt',
	'EastAsianWidth.txt': 'ucd/EastAsianWidth.txt',
	'DerivedGeneralCategory.txt': 'ucd/extracted/DerivedGeneralCategory.txt',
	'emoji-data.txt': 'ucd/emoji/emoji-data.txt',
	'LineBreakTest.txt': 'ucd/auxiliary/LineBreakTest.txt',
};
const files = {};
for (const [name, rel] of Object.entries(sources)) {
	const file = path.join(dir, name), url = `https://www.unicode.org/Public/${version}/${rel}`;
	if (!fs.existsSync(file)) {
		const r = spawnSync('curl', ['-fsSL', '--max-time', '60', url, '-o', file], {encoding: 'utf8'});
		if (r.status !== 0) throw Error(r.stderr);
	}
	files[name] = {url, sha256: crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')};
}
const outDir = 'src/helder/ui/flow';
const manifestFile = outDir + '/manifest.json';
if (fs.existsSync(manifestFile)) {
	const old = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
	for (const name of Object.keys(sources)) if (old.files[name] && old.files[name].sha256 !== files[name].sha256) throw Error('Unicode source hash changed: ' + name);
}

// (the classes in LineBreaks' order)
const CLASSES = 'XX BK CR LF CM NL SG WJ ZW GL SP ZWJ B2 BA BB HY HH CB CL CP EX IN NS OP QU IS NU PO PR SY AI AK AL AP AS CJ EB EM H2 H3 HL ID JL JV JT RI SA VF VI'.split(' ');
const N = 0x110000;
const cls = new Uint8Array(N), flags = new Uint8Array(N);
function ranges(name, each) {
	for (const line of fs.readFileSync(path.join(dir, name), 'utf8').split('\n')) {
		const missing = line.match(/^# @missing: ([0-9A-F.]+); (\S+)/);
		const body = missing ? missing[1] + ';' + missing[2] : line.split('#')[0];
		const f = body.split(';').map(s => s.trim());
		if (f.length < 2 || !f[0]) continue;
		const r = f[0].split('..').map(s => parseInt(s, 16));
		each(r[0], r[1] ?? r[0], f[1]);
	}
}
// (@missing lines first, in order: the defaults, then the listed values over them)
ranges('LineBreak.txt', (a, b, v) => {
	const k = CLASSES.indexOf(v);
	if (k < 0) throw Error('class ' + v);
	cls.fill(k, a, b + 1);
});
const EA = 1, PI = 2, PF = 4, PICT_CN = 8, MN = 16, MC = 32;
ranges('EastAsianWidth.txt', (a, b, v) => {
	for (let c = a; c <= b; c++) if (v === 'F' || v === 'W' || v === 'H') flags[c] |= EA; else flags[c] &= ~EA;
});
const cn = new Uint8Array(N);
ranges('DerivedGeneralCategory.txt', (a, b, v) => {
	for (let c = a; c <= b; c++) {
		if (v === 'Pi') flags[c] |= PI;
		if (v === 'Pf') flags[c] |= PF;
		if (v === 'Mn') flags[c] |= MN;
		if (v === 'Mc') flags[c] |= MC;
		cn[c] = v === 'Cn' ? 1 : 0;
	}
});
ranges('emoji-data.txt', (a, b, v) => {
	if (v !== 'Extended_Pictographic') return;
	for (let c = a; c <= b; c++) if (cn[c]) flags[c] |= PICT_CN;
});
// (what the rules read of a code point: its class and the flags that matter
// to it; Pi and Pf only for QU, Mn and Mc only for SA)
const QU = CLASSES.indexOf('QU'), SA = CLASSES.indexOf('SA');
const value = c => {
	let f = flags[c] & (EA | PICT_CN);
	if (cls[c] === QU) f |= flags[c] & (PI | PF);
	if (cls[c] === SA) f |= flags[c] & (MN | MC);
	return cls[c] | f << 6;
};
// (runs of equal values: each its length and value, base 36, "length.value,")
const runs = [];
let start = 0, v = value(0);
for (let c = 1; c <= N; c++) {
	const w = c < N ? value(c) : -1;
	if (w !== v) {
		runs.push((c - start).toString(36) + '.' + v.toString(36));
		start = c;
		v = w;
	}
}
const data = runs.join(',');
function literal(s) {
	const parts = [];
	for (let i = 0; i < s.length; i += 4096) parts.push(JSON.stringify(s.slice(i, i + 4096)));
	return parts.join(' +\n\t\t');
}
let out = 'package helder.ui.flow;\n\n// Generated by generate.mjs (beside it) from Unicode ' + version + ': each code point\'s\n// Line_Break class and flags (LineBreaks\' CLASS and its flags), as runs:\n// "length.value," in base 36. Unicode-3.0 license: helder.text.unicode\'s\n// LICENSE.txt; inputs and hashes: manifest.json.\nclass LineBreakData {\n';
out += '\tpublic static function runs():String\n\t\treturn ' + literal(data) + ';\n}\n';
fs.writeFileSync(outDir + '/LineBreakData.hx', out);

// (the sample: every line of the rules that decide fewer than 120
// boundaries, every 32nd of the rest; code points and marks alone)
const lines = fs.readFileSync(path.join(dir, 'LineBreakTest.txt'), 'utf8').split('\n').filter(l => l && l[0] !== '#');
const count = {};
for (const l of lines) for (const m of l.split('#')[1].matchAll(/\[([0-9.]+)\]/g)) count[m[1]] = (count[m[1]] ?? 0) + 1;
const sample = lines.filter((l, i) => i % 32 === 0 || [...l.split('#')[1].matchAll(/\[([0-9.]+)\]/g)].some(m => count[m[1]] < 120));
fs.mkdirSync('tests/flow', {recursive: true});
fs.writeFileSync('tests/flow/line-break-test.txt', '# A sample of LineBreakTest-' + version + '.txt (src/helder/ui/flow/generate.mjs): ÷ a break, × none\n' + sample.map(l => l.split('#')[0].trim()).join('\n') + '\n');
fs.writeFileSync(manifestFile, JSON.stringify({version, files, counts: {runs: runs.length, bytes: data.length, sample: sample.length, tests: lines.length}}, null, 2) + '\n');
console.log({version, runs: runs.length, bytes: data.length, sample: sample.length, tests: lines.length});
