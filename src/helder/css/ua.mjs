// Writes CssUserAgentData.hx: the HTML Standard's Rendering section's CSS
// (whatwg/html's source at REVISION, CC BY 4.0) and print.css beside this
// script; run from the repository's root: node src/helder/css/ua.mjs
//
// Its blocks by what the text before each says: the rules for every
// document, those for quirks mode, and those that apply as presentational
// hints (the cascade's `hints` option). Left out: the ISO-8859-8 encoding's
// bidi rules, the select element's appearances (forms are deferred), the
// details element's shadow tree. Rewritten: :heading as h1 to h6
// (Selectors 5's, not read yet). The tests' frozen #321 cascade gets the
// sheets with logical properties as physical ones (RefUserAgentData).
import fs from 'node:fs'
import crypto from 'node:crypto'
import {spawnSync} from 'node:child_process'

const REVISION = '0162cee0c42a82267354d38fbc6a2503ee295b77'
const dir = `bin/html-spec/${REVISION}`
const file = `${dir}/source`
fs.mkdirSync(dir, {recursive: true})
if (!fs.existsSync(file)) {
  const r = spawnSync('curl', ['-fsSL', '--max-time', '120', `https://raw.githubusercontent.com/whatwg/html/${REVISION}/source`, '-o', file], {encoding: 'utf8'})
  if (r.status !== 0) throw Error(r.stderr)
}
const src = fs.readFileSync(file, 'utf8')
const section = src.slice(src.indexOf('<h2 split-filename="rendering"'), src.indexOf('<h2 split-filename="obsolete"'))

const kinds = {base: [], quirks: [], hints: []}
const skipped = []
for (const m of section.matchAll(/<pre><code class="css">([\s\S]*?)<\/code><\/pre>/g)) {
  const before = section.slice(Math.max(0, m.index - 600), m.index).replace(/<[^>]+>/g, '')
  const heading = [...section.slice(0, m.index).matchAll(/<h[3-5][^>]*>([\s\S]*?)<\/h[3-5]>/g)].pop()?.[1].replace(/<[^>]+>/g, '') ?? ''
  const tail = before.replace(/\s+/g, ' ').trim().slice(-300)
  const css = decode(m[1].replace(/<!--[\s\S]*?-->/g, '').replace(/<[^>]+>/g, ''))
  if (/ISO-8859-8/.test(tail) || /select element/i.test(heading) || /third child element/.test(tail)) {
    skipped.push(heading.trim())
    continue
  }
  const kind = /presentational hints/.test(tail) ? 'hints' : /quirks mode/.test(tail) ? 'quirks' : 'base'
  kinds[kind].push(`/* ${heading.trim()} */\n${headings(css).trim()}`)
}
const print = fs.readFileSync('src/helder/css/print.css', 'utf8')
kinds.base.push(print.trim())
// (#321's frozen cascade, the tests' oracle, had no logical properties: its sheets physical)
const ref = `package reference;

// Generated by src/helder/css/ua.mjs: CssUserAgentData as #321's cascade
// had it, logical properties as physical ones (horizontal, left to right).
class RefUserAgentData {
\tpublic static final base = ${JSON.stringify(physical(kinds.base.join('\n\n')))};

\tpublic static final quirks = ${JSON.stringify(physical(kinds.quirks.join('\n\n')))};

\tpublic static final hints = ${JSON.stringify(physical(kinds.hints.join('\n\n')))};
}
`
fs.writeFileSync('tests/css/reference/RefUserAgentData.hx', ref)

const s = x => JSON.stringify(x)
const hx = `package helder.css;

// Generated by ua.mjs (beside it) from the HTML Standard's Rendering
// section (whatwg/html ${REVISION.slice(0, 12)}, CC BY 4.0) and print.css:
// the user agent's rules for every document, quirks mode's, and the
// presentational hints written as CSS.
class CssUserAgentData {
\tpublic static final base = ${s(kinds.base.join('\n\n'))};

\tpublic static final quirks = ${s(kinds.quirks.join('\n\n'))};

\tpublic static final hints = ${s(kinds.hints.join('\n\n'))};
}
`
fs.writeFileSync('src/helder/css/CssUserAgentData.hx', hx)
fs.writeFileSync('src/helder/css/ua.json', JSON.stringify({
  source: 'https://github.com/whatwg/html (source, the Rendering section)', revision: REVISION, license: 'CC BY 4.0',
  sha256: crypto.createHash('sha256').update(src).digest('hex'),
  blocks: {base: kinds.base.length - 1, quirks: kinds.quirks.length, hints: kinds.hints.length}, skipped
}, null, 2) + '\n')
console.log({base: kinds.base.length - 1, quirks: kinds.quirks.length, hints: kinds.hints.length, skipped: skipped.length})

function decode(t) {
  return t.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#x27;|&apos;/g, "'").replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
}

// (Selectors 5's :heading and :heading(n), which helder.css's selectors
// don't read yet: h1 to h6, a level's element)
function headings(css) {
  return css.replace(/:heading\(([\d,\s]+)\)/g, (all, levels) => {
    const hs = levels.split(',').map(x => Number(x.trim())).filter(n => n >= 1 && n <= 6).map(n => `h${n}`)
    return hs.length === 1 ? hs[0] : `:is(${hs.join(', ')})`
  }).replace(/:heading\b/g, ':is(h1, h2, h3, h4, h5, h6)')
}

// (block is top and bottom, inline left and right, start before end)
function physical(css) {
  const pairs = {block: ['top', 'bottom'], inline: ['left', 'right']}
  return css.replace(/([{;]\s*)(margin|padding|border|inset)-(block|inline)(-(start|end))?(-(width|style|color))?\s*:\s*([^;}]+)/g,
    (all, lead, prop, axis, _se, se, _k, k, value) => {
      const [a, b] = pairs[axis]
      const sides = se ? [se === 'start' ? a : b] : [a, b]
      const parts = value.trim().split(/\s+(?![^(]*\))/)
      const name = side => prop === 'inset' ? side : `${prop}-${side}${k ? '-' + k : ''}`
      if (se || prop === 'border') return lead + sides.map(side => `${name(side)}: ${value.trim()}`).join('; ')
      return lead + sides.map((side, i) => `${name(side)}: ${parts.length > 1 ? parts[i] : parts[0]}`).join('; ')
    })
    .replace(/([{;]\s*)(min-|max-)?(block|inline)-size\s*:/g, (all, lead, mm, axis) => `${lead}${mm ?? ''}${axis === 'block' ? 'height' : 'width'}:`)
}
