// Writes dictionary.bin and BrotliTables.hx (beside this file) from the
// brotli reference's sources, pinned (MIT, LICENSE-brotli.txt): RFC 7932's
// static dictionary, the literal context lookup table and the 121 word
// transforms.
//
//   node src/helder/compress/generate.mjs
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const REV = '717514a67b3f8abf53365d4471a102a60fff8ef5'
const here = path.dirname(new URL(import.meta.url).pathname)
const get = async (f, binary) => {
  const r = await fetch(`https://raw.githubusercontent.com/google/brotli/${REV}/${f}`)
  if (!r.ok) throw new Error(`${f}: ${r.status}`)
  return binary ? Buffer.from(await r.arrayBuffer()) : r.text()
}

const dictionary = await get('c/common/dictionary.bin', true)
// (RFC 7932's appendix A: the dictionary's SHA-256)
const sha = crypto.createHash('sha256').update(dictionary).digest('hex')
if (sha !== '20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70') throw new Error('dictionary: ' + sha)
fs.writeFileSync(path.join(here, 'dictionary.bin'), dictionary)
fs.writeFileSync(path.join(here, 'LICENSE-brotli.txt'), await get('LICENSE'))

const context = await get('c/common/context.c')
const lut = numbers(between(context, '_kBrotliContextLookupTable[2048] = {', '};'))
if (lut.length !== 2048) throw new Error('context: ' + lut.length)

const transform = await get('c/common/transform.c')
const strings = unescape([...between(transform, 'kPrefixSuffix[217] =', ';').replace(/\/\*.*?\*\//g, '').matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => m[1]).join(''))
strings.push(0)
const map = numbers(between(transform, 'kPrefixSuffixMap[50] = {', '};'))
const types = {IDENTITY: 0, UPPERCASE_FIRST: 10, UPPERCASE_ALL: 11}
for (let n = 1; n <= 9; n++) types[`OMIT_LAST_${n}`] = n, types[`OMIT_FIRST_${n}`] = 11 + n
const triples = between(transform, 'kTransformsData[] = {', '};').replace(/\/\*.*?\*\//g, '').split(',').map(s => s.trim()).filter(s => s)
  .map(s => /^\d+$/.test(s) ? Number(s) : types[s.replace('BROTLI_TRANSFORM_', '')])
if (triples.length !== 121 * 3 || triples.some(v => v === undefined)) throw new Error('transforms: ' + triples.length)
// (each affix as its bytes: a length, then the bytes)
const affix = i => {
  const at = map[i], n = strings[at]
  return strings.slice(at + 1, at + 1 + n)
}
const prefixes = [], suffixes = [], kinds = []
for (let t = 0; t < 121; t++) {
  prefixes.push(affix(triples[3 * t]))
  kinds.push(triples[3 * t + 1])
  suffixes.push(affix(triples[3 * t + 2]))
}

const rows = (a, per = 32) => Array.from({length: Math.ceil(a.length / per)}, (_, i) => '\t\t' + a.slice(i * per, i * per + per).join(', ')).join(',\n')
const list = a => '[' + a.map(b => '[' + b.join(', ') + ']').join(', ') + ']'
fs.writeFileSync(path.join(here, 'BrotliTables.hx'), `package helder.compress;

// Generated by generate.mjs (beside it) from the brotli reference at
// ${REV.slice(0, 12)} (MIT, LICENSE-brotli.txt): RFC 7932's literal context
// lookup table and its 121 word transforms.
@:noCompletion class BrotliTables {
	// (a context mode's 512 entries: the last byte's 256, then the one before's)
	public static final CONTEXT:Array<Int> = [
${rows(lut)}
	];

	// each transform's prefix bytes, kind (0 identity, 1-9 omit the last n,
	// 10 uppercase the first, 11 uppercase all, 12-20 omit the first n - 11)
	// and suffix bytes
	public static final PREFIXES:Array<Array<Int>> = ${list(prefixes)};
	public static final KINDS:Array<Int> = [${kinds.join(', ')}];
	public static final SUFFIXES:Array<Array<Int>> = ${list(suffixes)};
}
`)
console.log('dictionary.bin, BrotliTables.hx written')

function between(s, from, to) {
  const i = s.indexOf(from)
  if (i < 0) throw new Error('no ' + from)
  return s.slice(i + from.length, s.indexOf(to, i + from.length))
}

function numbers(s) {
  return s.replace(/\/\*.*?\*\//gs, '').split(',').map(x => x.trim()).filter(x => x).map(Number)
}

// (C's escapes: octal up to three digits, hex, the named ones)
function unescape(s) {
  const out = []
  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (c !== '\\') {
      out.push(c.charCodeAt(0))
      continue
    }
    const n = s[++i]
    if (/[0-7]/.test(n)) {
      let v = '', k = i
      while (k < s.length && v.length < 3 && /[0-7]/.test(s[k])) v += s[k++]
      out.push(parseInt(v, 8))
      i = k - 1
    } else if (n === 'x') {
      let v = '', k = i + 1
      while (k < s.length && /[0-9a-fA-F]/.test(s[k])) v += s[k++]
      out.push(parseInt(v, 16))
      i = k - 1
    } else out.push({n: 10, t: 9, '"': 34, "'": 39, '\\': 92}[n])
  }
  return out
}
